-- ============================================================
-- المرحلة 5 — منح ميزات الحضور للباقات القائمة
--
-- لماذا مهاجرة لا بذرة: `seedPlans` تنشئ الباقات الغائبة **ولا تدهس
-- الموجودة** عمداً (`update: {}`)، لأن الاسم والسعر والحد قرارات
-- تجارية يعدّلها مسؤول المنصة من اللوحة، وإعادة كتابتها في كل تهيئة
-- كانت تُرجعها إلى قيمها الافتتاحية.
--
-- لكن **ميزة جديدة في الكتالوج ليست قراراً تجارياً اتخذه المشغّل** —
-- هي قدرة أُضيفت للتو، ولو تُركت للبذرة لما وصلت إلى أي تثبيت قائم:
-- تبقى الباقات المدفوعة بلا توقيع بريد ولا محافظ، وتفشل كل شاشات
-- المرحلة 5 برسالة «غير متاح في باقتك» بلا سبب مفهوم.
--
-- ولذلك تُمنح هنا مرة واحدة، وتبقى قابلة للسحب من اللوحة بعدها.
--
-- الشرط `NOT (features @> …)` يجعلها قابلة لإعادة التشغيل بلا تكرار،
-- ولا تلمس باقة أضاف إليها المشغّل الميزة يدوياً قبل الترقية.
-- ============================================================

-- الاحترافية: نقاط تواصل **فردية**. المحترف المستقل يحتاج حضوره في
-- البريد والاجتماعات والمحفظة بقدر ما يحتاجه موظف مؤسسة.
UPDATE "plans"
SET "features" = "features" || ARRAY['email_signature', 'meeting_backgrounds', 'wallet_passes']
WHERE "key" = 'pro'
  AND NOT ("features" @> ARRAY['email_signature']);

-- الفرق والمؤسسات: الفردية **إضافةً إلى** الوسوم والحملات — كلتاهما
-- تُدار مركزياً ولا معنى لها لمن يدير نفسه.
UPDATE "plans"
SET "features" = "features" || ARRAY[
    'email_signature',
    'meeting_backgrounds',
    'wallet_passes',
    'nfc_tags',
    'campaigns'
]
WHERE "key" IN ('business', 'enterprise')
  AND NOT ("features" @> ARRAY['email_signature']);
