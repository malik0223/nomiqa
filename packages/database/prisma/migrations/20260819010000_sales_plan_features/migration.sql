-- ============================================================
-- المرحلة 6 — منح ميزات المبيعات للباقات القائمة
--
-- نفس مبرر مهاجرة `20260818010000_presence_plan_features`: `seedPlans`
-- لا تدهس باقة موجودة، فميزة جديدة في الكتالوج لن تصل إلى أي تثبيت
-- قائم لو تُركت للبذرة — وتبقى كل شاشات المرحلة 6 مقفلة برسالة «غير
-- متاح في باقتك» على مؤسسات دفعت للتو ثمن الباقة الأعلى.
--
-- الشرط `NOT (features @> …)` يجعلها قابلة لإعادة التشغيل بلا تكرار.
-- ============================================================

-- الاحترافية: المسح وحده.
--
-- المحترف المستقل يلتقي عملاء في مؤتمر ويجمع بطاقاتهم الورقية تماماً
-- كفريق مبيعات. أما الفعاليات والتكاملات فأدوات **فريق**: تقرير يقارن
-- أداء الأعضاء بلا أعضاء لا معنى له، ووصلة CRM تفترض نظاماً مؤسسياً
-- في الطرف الآخر.
UPDATE "plans"
SET "features" = "features" || ARRAY['card_scanning']
WHERE "key" = 'pro'
  AND NOT ("features" @> ARRAY['card_scanning']);

-- الأعمال: المسح والفعاليات والـWebhooks والـAPI.
--
-- مزامنة CRM خارجها عمداً: هي الميزة الوحيدة هنا التي تكتب في نظام
-- **طرف ثالث** نيابةً عن المؤسسة، وحصرها في الباقة العليا ليس تسعيراً
-- بقدر ما هو حصر لسطح الخطأ في مؤسسات لها من يديره.
UPDATE "plans"
SET "features" = "features" || ARRAY['card_scanning', 'events', 'webhooks', 'public_api']
WHERE "key" = 'business'
  AND NOT ("features" @> ARRAY['events']);

UPDATE "plans"
SET "features" = "features" || ARRAY[
    'card_scanning',
    'events',
    'webhooks',
    'public_api',
    'crm_sync'
]
WHERE "key" = 'enterprise'
  AND NOT ("features" @> ARRAY['events']);
